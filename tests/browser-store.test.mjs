import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import { createBrowserApi, scoreAttempt, summarize } from '../frontend/browser-store.js';

const corpus = JSON.parse(await fs.readFile(new URL('../data/corpus.json', import.meta.url), 'utf8'));
const memory = new Map();
const storage = { getItem: key => memory.get(key) ?? null, setItem: (key, value) => memory.set(key, value) };
const requested = [];
const options = { storage, baseUrl: new URL('https://example.github.io/TypeFlow/'), now: () => new Date(2026, 9, 28, 14, 30),
  fetcher: async url => { requested.push(url.href); return { ok: true, json: async () => corpus }; } };
const api = createBrowserApi(options);
const future = corpus.lessons.find(lesson => lesson.id === 'en-phrase-12');
const body = { lessonId: future.id, requestId: 'future-request-001', typed: future.text, elapsed: 10, errors: 25, mode: 'challenge' };
const submit = data => api('/api/attempts', { method: 'POST', body: JSON.stringify(data) });

assert.equal((await api('/api/stats')).totalAttempts, 0);
assert.equal((await api('/api/corpus')).lessons.length, 106);
assert.deepEqual(requested, ['https://example.github.io/TypeFlow/corpus.json']);
let data = await submit(body);
assert.equal(data.result.passed, true, 'future levels may be chosen before earlier levels');
assert.equal(data.result.accuracy, 100, 'corrected mistakes do not reduce accuracy');
assert.equal(data.result.score, 100);
assert.equal(data.stats.progress[future.id].attempts, 1);
assert.equal(data.stats.streak, 1);
assert.equal(data.stats.todaySeconds, 10);
assert.equal(data.stats.days.at(-1).date, '2026-10-28');
assert.equal(data.stats.days.at(-1).attempts, 1);
assert.equal(data.stats.history[0].created_at, '2026-10-28T14:30:00');
assert.equal((await submit(body)).stats.totalAttempts, 1, 'retries must not duplicate saved attempts');
const reloaded = createBrowserApi(options);
assert.equal((await reloaded('/api/stats')).progress[future.id].passed, true, 'refresh restores progress');
await submit({ ...body, requestId: 'free-request-001', lessonId: 'zh-phrase-01', typed: corpus.lessons.find(l => l.id === 'zh-phrase-01').text, mode: 'free' });
data = await api('/api/stats');
assert.equal(data.totalAttempts, 2);
assert.equal(data.progress['zh-phrase-01'], undefined, 'free practice does not add challenge stars');
const exported = await api('/api/export');
assert.equal(exported.app, 'typeflow');
assert.equal(exported.attempts.length, 2);
assert.equal(exported.attempts[0].request_id, body.requestId);
const isolated = createBrowserApi({ ...options, baseUrl: new URL('https://example.github.io/OtherSite/') });
assert.equal((await isolated('/api/stats')).totalAttempts, 0, 'different projects have separate progress');
assert.equal(scoreAttempt(future, future.text.slice(0, 2), 5).passed, false);
assert.throws(() => scoreAttempt(future, future.text, NaN), /时间/);
assert.throws(() => scoreAttempt(future, future.text, 5, -1), /错误数/);
assert.throws(() => scoreAttempt(future, future.text, 5, 0, 'invalid'), /模式/);
const blocked = createBrowserApi({ ...options, storage: { getItem: () => null, setItem: () => { throw new Error('QuotaExceededError'); } } });
await assert.rejects(blocked('/api/attempts', { method: 'POST', body: JSON.stringify(body) }), /成绩暂未保存/);
assert.equal((await blocked('/api/stats')).totalAttempts, 0, 'failed save cannot report a persisted result');
const corrupt = createBrowserApi({ ...options, storage: { getItem: () => '{broken' } });
await assert.rejects(corrupt('/api/stats'), /无法读取/);
const yesterday = { ...exported.attempts[0], created_at: '2026-10-27T10:00:00' };
assert.equal(summarize([yesterday], corpus.lessons, options.now()).streak, 1);
console.log('Pages browser storage tests passed: scoring, persistence, free selection, export, paths and storage errors.');
